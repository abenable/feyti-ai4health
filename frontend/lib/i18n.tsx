const LanguageContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: Dictionary;
} | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Server and client must render the same first paint, so the saved
  // preference is only applied after hydration.
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("feyti-language") as Language | null;
    // The saved preference is only available after hydration; setting it
    // here (not in a lazy initializer) keeps server/client markup aligned.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    if (saved && saved in dictionaries) setLanguageState(saved);
    document.documentElement.lang = saved && saved in dictionaries ? saved : "en";
  }, []);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem("feyti-language", next);
    document.documentElement.lang = next;
  }, []);

  const value = useMemo(
    () => ({ language, setLanguage, t: dictionaries[language] }),
    [language, setLanguage]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
